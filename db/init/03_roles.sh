#!/bin/sh
set -e

APP_USER="${APP_DB_USER:-ro_app}"
APP_PASS="${APP_DB_PASSWORD:-ChangeMeAppPass123!}"
EXP_USER="${EXPORTER_DB_USER:-postgres_exporter}"
EXP_PASS="${EXPORTER_DB_PASSWORD:-ChangeMeExporterPass123!}"
DB_NAME="${POSTGRES_DB:-ro_db}"

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$DB_NAME" <<-EOSQL
    DO \$\$
    BEGIN
        IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = '${APP_USER}') THEN
            CREATE ROLE ${APP_USER} WITH LOGIN PASSWORD '${APP_PASS}';
        ELSE
            ALTER ROLE ${APP_USER} WITH LOGIN PASSWORD '${APP_PASS}';
        END IF;

        IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = '${EXP_USER}') THEN
            CREATE ROLE ${EXP_USER} WITH LOGIN PASSWORD '${EXP_PASS}';
        ELSE
            ALTER ROLE ${EXP_USER} WITH LOGIN PASSWORD '${EXP_PASS}';
        END IF;
    END
    \$\$;

    REVOKE CREATE ON SCHEMA public FROM PUBLIC;
    REVOKE ALL ON DATABASE ${DB_NAME} FROM PUBLIC;

    GRANT CONNECT ON DATABASE ${DB_NAME} TO ${APP_USER};
    GRANT USAGE ON SCHEMA public TO ${APP_USER};
    GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO ${APP_USER};
    GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO ${APP_USER};
    ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${APP_USER};
    ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO ${APP_USER};

    GRANT CONNECT ON DATABASE ${DB_NAME} TO ${EXP_USER};
    GRANT pg_monitor TO ${EXP_USER};
EOSQL
